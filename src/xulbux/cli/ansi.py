        (_st("DOUBLE_UNDERLINE   "), S.DOUBLE_UNDERLINE("Text")),
        code('                   S.DOUBLE_UNDERLINE("Text")'),
        (_st("INVERSE            "), S.INVERSE("Text")),
        code('                   S.INVERSE("Text")'),
        (_st("HIDDEN             "), S.HIDDEN("Text")),
        code('                   S.HIDDEN("Text")'),
        (_st("STRIKETHROUGH      "), S.STRIKETHROUGH("Text")),
        code('                   S.STRIKETHROUGH("Text")'),
        "",
        title(" Foreground Colors ").center(*sep),
        "",
        (_st("BLACK              "), S.BLACK("Text")),
        code('                   S.BLACK("Text")'),
